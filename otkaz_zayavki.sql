-- =====================================================================
--  ОТКАЗ ПО ЗАЯВКЕ: новое состояние и причина
-- =====================================================================
--
--  До сих пор у заявки было два состояния: ждёт обработки и проведена.
--  Третьего — «отказано» — не было, и отказать оператор мог только на
--  словах, мимо системы: агент не узнавал причину, а в приложении
--  заявка висела в ожидании вечно.
--
--  Добавляем состояние 'rejected' и поле с причиной. Причина
--  обязательна на стороне приложения: отказ без объяснения приводит
--  к повторной такой же заявке через день.
--
--  Выполнять ДО выкатки нового api.py: без этих полей он работать
--  не будет.
--
--  КАК ЗАПУСКАТЬ — целиком, одной командой. В консоли Railway
--  (вкладка Console у базы) это выглядит так:
--
--      psql "$DATABASE_URL" -c "ВЕСЬ ТЕКСТ НИЖЕ ОДНОЙ СТРОКОЙ"
--
--  Либо файлом:  python vypolnit_sql.py otkaz_zayavki.sql --db "..."
--
-- =====================================================================

BEGIN;

-- Старое ограничение разрешало только два состояния и отвергло бы
-- 'rejected'. Имя у него стандартное, но на всякий случай снимаем по
-- имени из каталога, а не угадываем
ALTER TABLE operator_requests
    DROP CONSTRAINT IF EXISTS operator_requests_status_check;

ALTER TABLE operator_requests
    ADD CONSTRAINT operator_requests_status_check
    CHECK (status IN ('pending', 'done', 'rejected'));

-- Причина отказа. Для проведённых заявок остаётся пустой
ALTER TABLE operator_requests
    ADD COLUMN IF NOT EXISTS reason TEXT;

-- Архив открывают по дню, и отказы должны находиться там же, где
-- проведённые заявки
CREATE INDEX IF NOT EXISTS idx_oreq_status_done
    ON operator_requests (status, done_at DESC);

COMMIT;


-- ---------------------------------------------------------------------
--  Проверка: должно пройти без ошибки и показать три состояния
-- ---------------------------------------------------------------------
SELECT status, count(*) AS zayavok
  FROM operator_requests
 GROUP BY status
 ORDER BY status;
