-- ---------- 1. Статус точки ----------
-- 0 = активная (по умолчанию), 1 = пассивная
ALTER TABLE client_base
    ADD COLUMN IF NOT EXISTS status SMALLINT NOT NULL DEFAULT 0;

-- ---------- 2. Исходный ИНН ----------
-- В выгрузке ИНН пассивных точек помечены символами: "306955509+",
-- "+629441139", "306822032++". Искать по ним нельзя — агент вводит только
-- цифры. Поэтому в inn храним очищенные цифры, а исходное значение
-- со всеми пометками остаётся здесь, чтобы ничего не потерялось.
ALTER TABLE client_base
    ADD COLUMN IF NOT EXISTS inn_raw TEXT;

-- ---------- 3. Поиск похожих названий ----------
-- pg_trgm умеет сравнивать строки по сходству: similarity('MUXAYYO TRADE',
-- 'MUHAYO TRADE') = 0.5. Нужен, чтобы ловить опечатки в названиях.
CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- Индекс для быстрого поиска похожих названий по всей базе
CREATE INDEX IF NOT EXISTS idx_client_base_name_trgm
    ON client_base USING gin (point_name gin_trgm_ops);

-- ---------- 4. Лишний индекс ----------
-- UNIQUE на inn уже создаёт индекс, отдельный только занимал место
DROP INDEX IF EXISTS idx_client_base_inn;

